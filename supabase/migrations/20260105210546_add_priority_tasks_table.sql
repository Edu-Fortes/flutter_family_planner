-- 1. Create Tasks Table
create table public.priority_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  priority int default 3, -- 1=High, 2=Medium, 3=Low
  is_completed boolean default false,
  created_at timestamptz default now()
);

-- 2. Security Policies
alter table public.priority_tasks enable row level security;

create policy "Anyone can read tasks" on public.priority_tasks for select using (true);
create policy "Anyone can insert tasks" on public.priority_tasks for insert with check (true);
create policy "Anyone can update tasks" on public.priority_tasks for update using (true);
create policy "Anyone can delete tasks" on public.priority_tasks for delete using (true);