-- 1. Create the table
create table public.daily_quotes (
  id bigint generated by default as identity primary key,
  autor text,
  frase text
);

-- 2. Enable RLS (Security)
alter table public.daily_quotes enable row level security;

-- 3. Create a policy so everyone can READ quotes
create policy "Anyone can read quotes"
on public.daily_quotes for select
to authenticated, anon
using (true);

-- 4. Create the "Quote of the Day" logic
-- This function calculates which row to pick based on the current day of the year.
-- This guarantees the same quote for everyone, changing only at midnight.
create or replace function get_daily_quote()
returns setof public.daily_quotes
set search_path = ''
as $$
declare
  count_quotes int;
  day_of_year int;
  row_offset int;
begin
  -- Get total number of quotes
  select count(*) into count_quotes from public.daily_quotes;

  -- Get current day of year (1 to 365/366)
  -- We subtract 1 because OFFSET starts at 0
  day_of_year := extract(doy from now())::int - 1;

  -- Calculate robust offset (Day % Total) so it loops if we run out of quotes
  -- or works even if we have fewer than 365 quotes.
  if count_quotes > 0 then
    row_offset := day_of_year % count_quotes;
    return query select * from public.daily_quotes offset row_offset limit 1;
  end if;
end;
$$ language plpgsql;